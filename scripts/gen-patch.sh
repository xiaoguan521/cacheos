#!/usr/bin/env bash
# 由 dataplane/rename/rename.py 在干净的上游源码上生成改名 patch（规格书 5.1）。
#
# 用法：scripts/gen-patch.sh [-s <上游源码目录>] [-c]
#   -s  使用已有的上游源码（必须是 UPSTREAM_TAG 的干净检出）；不指定则按 dataplane/UPSTREAM 拉取并校验提交哈希
#   -c  只检查：重新生成并与仓库中的 patch 比对，不一致即失败（CI 用）
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck disable=SC1091
source "$ROOT/dataplane/UPSTREAM"
PATCH="$ROOT/dataplane/patches/0001-sycache-rename.patch"

SRC=""; CHECK=0
while getopts "s:c" opt; do
  case "$opt" in
    s) SRC="$OPTARG" ;;
    c) CHECK=1 ;;
    *) exit 2 ;;
  esac
done

WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
if [[ -z "$SRC" ]]; then
  git -c advice.detachedHead=false clone -q --depth 1 --branch "$UPSTREAM_TAG" "$UPSTREAM_GIT" "$WORK/a"
  got="$(git -C "$WORK/a" rev-parse HEAD)"
  [[ "$got" == "$UPSTREAM_COMMIT" ]] || { echo "upstream commit mismatch: $got != $UPSTREAM_COMMIT" >&2; exit 3; }
else
  cp -a "$SRC" "$WORK/a"
fi
rm -rf "$WORK/a/.git"
grep -q "#define VALKEY_VERSION \"$UPSTREAM_VERSION\"" "$WORK/a/src/version.h" \
  || { echo "source is not valkey $UPSTREAM_VERSION" >&2; exit 3; }
cp -a "$WORK/a" "$WORK/b"
python3 "$ROOT/dataplane/rename/rename.py" "$WORK/b" >&2

{
  echo "CacheOS sycache rename patch for valkey $UPSTREAM_VERSION ($UPSTREAM_COMMIT)."
  echo "Generated by scripts/gen-patch.sh from dataplane/rename/rename.py. Do not edit by hand."
  echo
  # 去掉文件头里的时间戳，保证同一输入生成逐字节相同的 patch
  (cd "$WORK" && { diff -ruN a b || [[ $? -eq 1 ]]; } | sed -E 's/^((---|\+\+\+) [^\t]+)\t.*$/\1/')
} > "$WORK/out.patch"

if [[ $CHECK -eq 1 ]]; then
  diff -u "$PATCH" "$WORK/out.patch" >/dev/null \
    || { echo "rename patch is stale: run scripts/gen-patch.sh and commit" >&2; exit 1; }
  echo "rename patch up to date"
else
  mkdir -p "$(dirname "$PATCH")"
  cp "$WORK/out.patch" "$PATCH"
  echo "wrote $PATCH ($(grep -c '^+++ ' "$PATCH") files)"
fi
